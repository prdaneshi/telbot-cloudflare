#!/usr/bin/env node

/**
 * Validate a data-driven test definition and build a D1 SQL seed file.
 *
 * Usage:
 *   node scripts/build-test-sql.mjs test-data/neo.json migrations/0002_neo.sql
 */

import { readFile, writeFile } from "node:fs/promises";

const [, , inputPath, outputPath] = process.argv;
if (!inputPath || !outputPath) {
  console.error("Usage: node scripts/build-test-sql.mjs <input.json> <output.sql>");
  process.exit(1);
}

const fail = (message) => {
  throw new Error(`Invalid test definition: ${message}`);
};

const sql = (value) => {
  if (value === null || value === undefined) return "NULL";
  if (typeof value === "boolean") return value ? "1" : "0";
  if (typeof value === "number") {
    if (!Number.isFinite(value)) fail(`non-finite number: ${value}`);
    return String(value);
  }
  return `'${String(value).replaceAll("'", "''")}'`;
};

const active = (value) => (value === false ? 0 : 1);
const sortOrder = (value, fallback = 0) => Number.isInteger(value) ? value : fallback;
const sorted = (items, label) => [...items].sort((a, b) => {
  const difference = sortOrder(a.position ?? a.sort_order) - sortOrder(b.position ?? b.sort_order);
  if (difference !== 0) return difference;
  return String(a[label] ?? "").localeCompare(String(b[label] ?? ""));
});

const raw = JSON.parse(await readFile(inputPath, "utf8"));
const test = raw;
if (!test || typeof test !== "object") fail("root must be an object");
if (!test.id || !/^[a-z0-9][a-z0-9_-]*$/.test(test.id)) fail("id must use lowercase letters, numbers, _ or -");
if (!test.title) fail("title is required");
if (!test.version?.label) fail("version.label is required");
if (!Array.isArray(test.dimensions) || test.dimensions.length === 0) fail("at least one dimension is required");
if (!Array.isArray(test.options) || test.options.length < 2) fail("at least two options are required");
if (!Array.isArray(test.questions) || test.questions.length === 0) fail("at least one question is required");

const unique = (items, key, label) => {
  const values = items.map((item) => item[key]);
  if (values.some((value) => value === undefined || value === null || value === "")) fail(`${label}.${key} is required`);
  if (new Set(values).size !== values.length) fail(`${label}.${key} values must be unique`);
};

unique(test.dimensions, "key", "dimensions");
unique(test.options, "position", "options");
unique(test.questions, "position", "questions");
const dimensionKeys = new Set(test.dimensions.map((dimension) => dimension.key));
const positions = (items, label) => {
  const values = [...items].map((item) => item.position).sort((a, b) => a - b);
  values.forEach((value, index) => {
    if (value !== index) fail(`${label}.position must be contiguous and zero-based (expected ${index}, got ${value})`);
  });
};
positions(test.options, "options");
positions(test.questions, "questions");

for (const [index, question] of test.questions.entries()) {
  if (!question.text) fail(`questions[${index}].text is required`);
  if (!Array.isArray(question.scoring) || question.scoring.length === 0) fail(`questions[${index}].scoring is required`);
  for (const scoring of question.scoring) {
    if (!dimensionKeys.has(scoring.dimension)) fail(`questions[${index}] references unknown dimension ${scoring.dimension}`);
    if (scoring.weight !== undefined && (typeof scoring.weight !== "number" || !Number.isFinite(scoring.weight))) {
      fail(`questions[${index}].scoring.weight must be a number`);
    }
  }
}

const scaleMin = Number(test.version.scale?.min ?? 0);
const scaleMax = Number(test.version.scale?.max ?? 4);
if (!Number.isFinite(scaleMin) || !Number.isFinite(scaleMax) || scaleMin >= scaleMax) fail("version.scale must have min < max");

const versionWhere = `(SELECT id FROM test_versions WHERE test_id = ${sql(test.id)} AND version_label = ${sql(test.version.label)})`;
const dimensionWhere = (key) => `(SELECT id FROM dimensions WHERE test_version_id = ${versionWhere} AND key = ${sql(key)})`;
const lines = [
  "-- Generated by scripts/build-test-sql.mjs. Review before applying to D1.",
  "PRAGMA foreign_keys = ON;",
  "BEGIN TRANSACTION;",
  `INSERT INTO tests (id, title, description, active, sort_order) VALUES (${sql(test.id)}, ${sql(test.title)}, ${sql(test.description || "")}, ${active(test.active)}, ${sortOrder(test.sortOrder)}) ON CONFLICT(id) DO UPDATE SET title = excluded.title, description = excluded.description, active = excluded.active, sort_order = excluded.sort_order;`,
  `INSERT INTO test_versions (test_id, version_label, instructions, question_count, scale_min, scale_max, active) VALUES (${sql(test.id)}, ${sql(test.version.label)}, ${sql(test.version.instructions || "")}, ${test.questions.length}, ${scaleMin}, ${scaleMax}, ${active(test.version.active)}) ON CONFLICT(test_id, version_label) DO UPDATE SET instructions = excluded.instructions, question_count = excluded.question_count, scale_min = excluded.scale_min, scale_max = excluded.scale_max, active = excluded.active;`,
  "",
  `DELETE FROM result_interpretations WHERE test_version_id = ${versionWhere};`,
  `DELETE FROM question_scoring WHERE question_id IN (SELECT id FROM questions WHERE test_version_id = ${versionWhere});`,
  `DELETE FROM questions WHERE test_version_id = ${versionWhere};`,
  `DELETE FROM options WHERE test_version_id = ${versionWhere};`,
  `DELETE FROM dimensions WHERE test_version_id = ${versionWhere};`,
  "",
];

for (const [index, dimension] of sorted(test.dimensions, "key").entries()) {
  lines.push(`INSERT INTO dimensions (test_version_id, key, title, description, sort_order) VALUES (${versionWhere}, ${sql(dimension.key)}, ${sql(dimension.title || dimension.key)}, ${sql(dimension.description || "")}, ${sortOrder(dimension.sortOrder, index)});`);
}
for (const option of sorted(test.options, "label")) {
  if (typeof option.value !== "number" || !Number.isFinite(option.value)) fail(`options[${option.position}].value must be a number`);
  lines.push(`INSERT INTO options (test_version_id, position, label, value) VALUES (${versionWhere}, ${option.position}, ${sql(option.label)}, ${option.value});`);
}
for (const question of sorted(test.questions, "text")) {
  lines.push(`INSERT INTO questions (test_version_id, position, text) VALUES (${versionWhere}, ${question.position}, ${sql(question.text)});`);
  const questionWhere = `(SELECT id FROM questions WHERE test_version_id = ${versionWhere} AND position = ${question.position})`;
  for (const scoring of question.scoring) {
    lines.push(`INSERT INTO question_scoring (question_id, dimension_id, weight, reverse_scored) VALUES (${questionWhere}, ${dimensionWhere(scoring.dimension)}, ${Number(scoring.weight ?? 1)}, ${scoring.reverse ? 1 : 0});`);
  }
}
for (const interpretation of test.interpretations || []) {
  if (!dimensionKeys.has(interpretation.dimension)) fail(`interpretations references unknown dimension ${interpretation.dimension}`);
  if (typeof interpretation.min !== "number" || typeof interpretation.max !== "number" || interpretation.min > interpretation.max) {
    fail(`interpretations for ${interpretation.dimension} must have valid min/max`);
  }
  if (!interpretation.text) fail(`interpretation text is required for ${interpretation.dimension}`);
  lines.push(`INSERT INTO result_interpretations (test_version_id, dimension_id, min_score, max_score, level, text) VALUES (${versionWhere}, ${dimensionWhere(interpretation.dimension)}, ${interpretation.min}, ${interpretation.max}, ${sql(interpretation.level || "")}, ${sql(interpretation.text)});`);
}
lines.push("COMMIT;", "");

await writeFile(outputPath, `${lines.join("\n")}\n`, "utf8");
console.log(`Validated ${test.questions.length} questions, ${test.dimensions.length} dimensions and ${test.options.length} options.`);
console.log(`SQL written to ${outputPath}`);
